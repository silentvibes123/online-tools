// ===== AGE CALCULATOR =====
function calculateAge() {
  const dob = new Date(document.getElementById("dob").value);
  const target = new Date(document.getElementById("todayDate").value);
  if (!document.getElementById("dob").value) return showNotify("error","Select Date of Birth!");
  if (dob > target) return showNotify("error","DOB cannot be in the future!");

  let y = target.getFullYear() - dob.getFullYear();
  let m = target.getMonth() - dob.getMonth();
  let d = target.getDate() - dob.getDate();
  if (d < 0) { m--; d += new Date(target.getFullYear(), target.getMonth(), 0).getDate(); }
  if (m < 0) { y--; m += 12; }

  document.getElementById("ageResult").classList.remove("d-none");
  document.getElementById("mainAge").innerText = `${y} Years`;
  document.getElementById("extraAge").innerText = `${m} Months, ${d} Days`;
  const diff = Math.abs(target - dob);
  document.getElementById("totalMonths").innerText = (y*12+m).toLocaleString();
  document.getElementById("totalWeeks").innerText = Math.floor(diff/(1000*60*60*24*7)).toLocaleString();
  document.getElementById("totalDays").innerText = Math.floor(diff/(1000*60*60*24)).toLocaleString();
  showNotify("success","Age Calculated!");
}

