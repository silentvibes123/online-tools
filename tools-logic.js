function convertUnit() {
  const cat = document.getElementById("ucCategory").value;
  const from = document.getElementById("ucFrom").value;
  const to = document.getElementById("ucTo").value;
  const val = parseFloat(document.getElementById("ucValue").value);
  if (isNaN(val)) { document.getElementById("ucResult").value = ""; return; }
  let result;
  if (cat === "temperature") {
    let celsius;
    if (from === "celsius") celsius = val;
    else if (from === "fahrenheit") celsius = (val-32)*5/9;
    else celsius = val - 273.15;
    if (to === "celsius") result = celsius;
    else if (to === "fahrenheit") result = celsius*9/5+32;
    else result = celsius + 273.15;
  } else {
    const base = val / UC_UNITS[cat][from];
    result = base * UC_UNITS[cat][to];
  }
  document.getElementById("ucResult").value = parseFloat(result.toFixed(6));
}

