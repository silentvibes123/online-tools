function generatePassword() {
  const len = +document.getElementById("pwdLen").value;
  const upper = document.getElementById("pwdUpper").checked;
  const lower = document.getElementById("pwdLower").checked;
  const num = document.getElementById("pwdNum").checked;
  const sym = document.getElementById("pwdSym").checked;
  if (!upper && !lower && !num && !sym) return showNotify("error","Select at least one character type!");
  let chars = "";
  if (upper) chars += "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  if (lower) chars += "abcdefghijklmnopqrstuvwxyz";
  if (num) chars += "0123456789";
  if (sym) chars += "!@#$%^&*()_+-=[]{}|;:,.<>?";
  let pwd = "";
  for (let i = 0; i < len; i++) pwd += chars[Math.floor(Math.random() * chars.length)];
  document.getElementById("pwdOutput").value = pwd;
  // Strength
  const strength = [upper,lower,num,sym].filter(Boolean).length;
  const pct = [0,25,50,75,100][strength];
  const colors = ["","#dc3545","#fd7e14","#ffc107","#198754"];
  const labels = ["","Weak","Fair","Good","Strong"];
  const bar = document.getElementById("pwdStrBar");
  bar.style.width = pct+"%"; bar.style.background = colors[strength];
  document.getElementById("pwdStrLabel").innerText = labels[strength];
  document.getElementById("pwdStrLabel").style.color = colors[strength];
  document.getElementById("pwdStrength").classList.remove("d-none");
}

